/*
assignment operators
*/

let stock = 500;

// printing the current stock available
console.log(
    "Current stock: ", stock
);

// adding stock to the available one

stock += 150

console.log(
    "New stock available: ", stock
);


// after dispensing some drugs

stock -= 75;

console.log(
    "After dispensing: ", stock
);


// after multiplication
stock *= 2

console.log(
    "After multiplication: ", stock
);


// remainder after some divisions

stock %= 7;

console.log(
    "Remainder after division: ", stock
);